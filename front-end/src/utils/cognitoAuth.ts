const STORAGE_KEY = 'moaz_admin_auth';
const CONFIG_KEY = 'moaz_cognito_config';

export type CognitoAuthSession = {
  idToken: string;
  accessToken: string;
  refreshToken?: string;
  expiresAt: number;
  email: string;
};

export type CognitoLoginResult =
  | { status: 'SUCCESS'; session: CognitoAuthSession }
  | { status: 'NEW_PASSWORD_REQUIRED'; sessionToken: string; username: string }
  | { status: 'PASSWORD_RESET_REQUIRED'; username: string };

export async function discoverCognitoConfig(): Promise<{ region: string; clientId: string }> {
  // 1. Check build-time Vite env
  if (import.meta.env.VITE_COGNITO_CLIENT_ID) {
    return {
      region: import.meta.env.VITE_COGNITO_REGION || 'us-east-1',
      clientId: import.meta.env.VITE_COGNITO_CLIENT_ID,
    };
  }

  // 2. Fetch runtime /auth-config.json generated by Terraform in S3
  try {
    const res = await fetch('/auth-config.json', { cache: 'no-store' });
    if (res.ok) {
      const data = await res.json();
      if (data.clientId) {
        localStorage.setItem(CONFIG_KEY, JSON.stringify({ region: data.region || 'us-east-1', clientId: data.clientId }));
        return { region: data.region || 'us-east-1', clientId: data.clientId };
      }
    }
  } catch {
    // Ignore and try /api/portfolio
  }

  // 3. Fallback to /api/portfolio authConfig block
  try {
    const res = await fetch('/api/portfolio');
    if (res.ok) {
      const data = await res.json();
      if (data?.authConfig?.clientId) {
        return {
          region: data.authConfig.region || 'us-east-1',
          clientId: data.authConfig.clientId,
        };
      }
    }
  } catch {
    // Ignore
  }

  const saved = localStorage.getItem(CONFIG_KEY);
  const parsed = saved ? JSON.parse(saved) : {};
  return {
    region: parsed.region || 'us-east-1',
    clientId: parsed.clientId || '',
  };
}

export function getStoredSession(): CognitoAuthSession | null {
  try {
    const raw = sessionStorage.getItem(STORAGE_KEY);
    if (!raw) return null;
    const session: CognitoAuthSession = JSON.parse(raw);
    if (Date.now() >= session.expiresAt) {
      sessionStorage.removeItem(STORAGE_KEY);
      return null;
    }
    return session;
  } catch {
    return null;
  }
}

export function clearSession() {
  sessionStorage.removeItem(STORAGE_KEY);
}

class CognitoApiError extends Error {
  code: string;
  constructor(code: string, message: string) {
    super(message);
    this.code = code;
  }
}

async function cognitoRequest(region: string, target: string, body: Record<string, unknown>) {
  const endpoint = `https://cognito-idp.${region}.amazonaws.com/`;
  const res = await fetch(endpoint, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/x-amz-json-1.1',
      'X-Amz-Target': `AWSCognitoIdentityProviderService.${target}`,
    },
    body: JSON.stringify(body),
  });
  const data = await res.json();
  if (!res.ok) {
    const rawType = String(data.__type || '');
    const code = rawType.includes('#') ? rawType.split('#')[1] : rawType;
    throw new CognitoApiError(code, data.message || code || 'Authentication failed');
  }
  return data;
}

export async function signInWithCognito(
  email: string,
  password: string,
  region: string,
  clientId: string
): Promise<CognitoLoginResult> {
  try {
    const data = await cognitoRequest(region, 'InitiateAuth', {
      AuthFlow: 'USER_PASSWORD_AUTH',
      ClientId: clientId,
      AuthParameters: {
        USERNAME: email.trim(),
        PASSWORD: password,
      },
    });

    if (data.ChallengeName === 'NEW_PASSWORD_REQUIRED') {
      return {
        status: 'NEW_PASSWORD_REQUIRED',
        sessionToken: data.Session,
        username: email.trim(),
      };
    }

    const auth = data.AuthenticationResult;
    const session: CognitoAuthSession = {
      idToken: auth.IdToken,
      accessToken: auth.AccessToken,
      refreshToken: auth.RefreshToken,
      expiresAt: Date.now() + (auth.ExpiresIn || 3600) * 1000,
      email: email.trim(),
    };
    sessionStorage.setItem(STORAGE_KEY, JSON.stringify(session));
    return { status: 'SUCCESS', session };
  } catch (err: any) {
    if (err instanceof CognitoApiError && err.code === 'PasswordResetRequiredException') {
      return {
        status: 'PASSWORD_RESET_REQUIRED',
        username: email.trim(),
      };
    }
    throw err;
  }
}

export async function completeNewPasswordChallenge(
  username: string,
  newPassword: string,
  sessionToken: string,
  region: string,
  clientId: string
): Promise<CognitoAuthSession> {
  const data = await cognitoRequest(region, 'RespondToAuthChallenge', {
    ChallengeName: 'NEW_PASSWORD_REQUIRED',
    ClientId: clientId,
    Session: sessionToken,
    ChallengeResponses: {
      USERNAME: username,
      NEW_PASSWORD: newPassword,
    },
  });

  const auth = data.AuthenticationResult;
  const session: CognitoAuthSession = {
    idToken: auth.IdToken,
    accessToken: auth.AccessToken,
    refreshToken: auth.RefreshToken,
    expiresAt: Date.now() + (auth.ExpiresIn || 3600) * 1000,
    email: username,
  };
  sessionStorage.setItem(STORAGE_KEY, JSON.stringify(session));
  return session;
}

export async function requestForgotPasswordCode(
  email: string,
  region: string,
  clientId: string
): Promise<void> {
  await cognitoRequest(region, 'ForgotPassword', {
    ClientId: clientId,
    Username: email.trim(),
  });
}

export async function confirmForgotPasswordWithCode(
  email: string,
  verificationCode: string,
  newPassword: string,
  region: string,
  clientId: string
): Promise<void> {
  await cognitoRequest(region, 'ConfirmForgotPassword', {
    ClientId: clientId,
    Username: email.trim(),
    ConfirmationCode: verificationCode.trim(),
    Password: newPassword,
  });
}
